CREATE TABLE checkout_orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES users(user_id) ON DELETE SET NULL,
    request_scope text NOT NULL,
    request_hash char(64) NOT NULL,
    guest_token_salt uuid,
    guest_token_hash char(64),
    stripe_request_key uuid NOT NULL UNIQUE,
    stripe_session_id text UNIQUE,
    stripe_checkout_url text,
    frontend_url text NOT NULL,
    line_items jsonb NOT NULL,
    total_cents bigint NOT NULL CHECK (total_cents BETWEEN 50 AND 99999999),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (request_scope, request_hash),
    CHECK ((guest_token_salt IS NULL) = (guest_token_hash IS NULL)),
    CHECK ((stripe_session_id IS NULL) = (stripe_checkout_url IS NULL))
);
